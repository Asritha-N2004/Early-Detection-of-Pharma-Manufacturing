"""Legible, paginated preliminary reports with escaped untrusted evidence text."""
from io import BytesIO
import json
from pathlib import Path
from xml.sax.saxutils import escape
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet,ParagraphStyle
from reportlab.lib.enums import TA_LEFT
from reportlab.platypus import SimpleDocTemplate,Paragraph,Spacer,Table,TableStyle,KeepTogether
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

def render_report(item):
    font='Helvetica'
    for path in [Path('C:/Windows/Fonts/arial.ttf'),Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')]:
        if path.exists():
            if 'ReportBody' not in pdfmetrics.getRegisteredFontNames():pdfmetrics.registerFont(TTFont('ReportBody',str(path)))
            font='ReportBody';break
    output=BytesIO();styles=getSampleStyleSheet()
    for name in ['Normal','Title','Heading1','Heading2','BodyText']:
        styles[name].fontName=font
    styles['Normal'].fontSize=9;styles['Normal'].leading=13
    styles.add(ParagraphStyle('Label',fontName=font,fontSize=8,textColor=colors.HexColor('#617795'),leading=11))
    styles['Title'].fontSize=23;styles['Title'].textColor=colors.HexColor('#173255')
    styles['Heading2'].fontSize=12;styles['Heading2'].textColor=colors.HexColor('#285998')
    def text(value):
        if isinstance(value,(dict,list)):value=json.dumps(value,ensure_ascii=False,indent=2)
        return Paragraph(escape(str(value)).replace('\n','<br/>'),styles['Normal'])
    def grid(rows,widths):
        table=Table([[text(v) for v in row] for row in rows],colWidths=widths,repeatRows=1,hAlign='LEFT')
        table.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),colors.HexColor('#eaf0f8')),('GRID',(0,0),(-1,-1),.3,colors.HexColor('#dae3ee')),('VALIGN',(0,0),(-1,-1),'TOP'),('LEFTPADDING',(0,0),(-1,-1),6),('RIGHTPADDING',(0,0),(-1,-1),6),('TOPPADDING',(0,0),(-1,-1),6),('BOTTOMPADDING',(0,0),(-1,-1),6)]))
        return table
    content=item['content'];story=[Paragraph('PharmaSignal',styles['Title']),Paragraph(item.get('family','deviation').replace('_',' ').title()+' report',styles['Heading2']),text(item['notice']),Spacer(1,14)]
    metadata=[['Report ID',item['id']],['Generated',item['created']],['Generated by',item['generated_by']],['Process',content.get('process','See evidence below')],['Batch',content.get('batch','See evidence below')],['Synthetic data',content.get('synthetic','See source records')],['Human review',content.get('status','Required')]]
    table=Table([[text(k),text(v)] for k,v in metadata],colWidths=[110,380],hAlign='LEFT')
    table.setStyle(TableStyle([('BACKGROUND',(0,0),(0,-1),colors.HexColor('#eef3f9')),('GRID',(0,0),(-1,-1),.3,colors.HexColor('#dae3ee')),('VALIGN',(0,0),(-1,-1),'TOP'),('LEFTPADDING',(0,0),(-1,-1),9),('RIGHTPADDING',(0,0),(-1,-1),9),('TOPPADDING',(0,0),(-1,-1),7),('BOTTOMPADDING',(0,0),(-1,-1),7)]));story.append(table)
    for key,value in content.items():
        if key in ['id','process','batch','synthetic','status']:continue
        story.extend([Spacer(1,14),Paragraph(escape(key.replace('_',' ').title()),styles['Heading2'])])
        if key=='findings' and isinstance(value,list):
            selected=[f for f in value if f.get('flag')]
            story.append(grid([['Parameter','Value','Range','Reference','Score','Evidence']]+[[f['parameter'],round(f['value'],4),f"{f['low']} to {f['high']}",round(f['baseline'],4),round(f['score'],3),f['explanation']] for f in selected],[75,50,70,55,45,195]))
            story.append(text('Scores are uncalibrated screening indicators. Only affected parameters are listed.'))
            continue
        if key=='risk' and isinstance(value,dict):
            story.append(grid([['Risk factor','Assessment']]+[[k.replace('_',' ').title(),v] for k,v in value.items()],[140,350]));continue
        if key=='hypotheses' and isinstance(value,list):
            for hypothesis in value:
                story.extend([Paragraph(escape(hypothesis['cause']),styles['Heading2']),text(hypothesis['evidence']),text('Supporting parameters: '+', '.join(hypothesis.get('supporting_parameters',[])))])
                for limitation in hypothesis.get('limitations',[]):story.append(text('Limitation: '+limitation))
                if hypothesis.get('equipment_evidence'):story.append(text('Retrieved equipment evidence: '+json.dumps(hypothesis['equipment_evidence'],ensure_ascii=False)))
                story.append(Spacer(1,8))
            continue
        if isinstance(value,list):
            for index,entry in enumerate(value):
                story.append(text(entry));story.append(Spacer(1,7))
        else:story.append(text(value))
    story.extend([Spacer(1,15),Paragraph('Limitations & review requirements',styles['Heading2'])])
    for limitation in item['limitations']:story.append(text('• '+limitation))
    def page(canvas,doc):
        canvas.setFont(font,7);canvas.setFillColor(colors.HexColor('#788ca8'))
        canvas.drawString(42,28,'AI-GENERATED • HUMAN REVIEW REQUIRED • NOT A GMP APPROVAL')
        canvas.drawRightString(550,28,f'Page {doc.page}')
    SimpleDocTemplate(output,pagesize=(595,842),leftMargin=45,rightMargin=45,topMargin=42,bottomMargin=48,title='PharmaSignal preliminary report',author='PharmaSignal decision support').build(story,onFirstPage=page,onLaterPages=page)
    return output.getvalue()
